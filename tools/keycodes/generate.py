#!/usr/bin/env python3
"""Generate crates/keyvo-core/src/chord/keycodes.rs from the KEY_* defines of
the Linux uapi header linux/input-event-codes.h.

Usage, from the repository root (the dev image has the header):

    python3 tools/keycodes/generate.py [/usr/include/linux/input-event-codes.h]

Then update the linux-libc-dev version in the generated header comment if the
header changed, and run `just fmt lint test`.
"""

import re
import sys
from pathlib import Path

HEADER = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h"
OUT = Path(__file__).resolve().parents[2] / "crates/keyvo-core/src/chord/keycodes.rs"
SKIP = {"KEY_RESERVED", "KEY_MIN_INTERESTING", "KEY_MAX", "KEY_CNT"}
LIBC_DEV = "6.12.113"

values = {}
for line in open(HEADER, encoding="utf-8"):
    match = re.match(r"#define\s+(KEY_[A-Z0-9_]+)\s+(\S+)", line)
    if not match:
        continue
    name, value = match.groups()
    if name in SKIP:
        continue
    if value.startswith("KEY_"):
        if value not in values:
            continue
        values[name] = values[value]
    else:
        values[name] = int(value, 0)

rows = sorted((name[4:].lower(), code) for name, code in values.items())
lines = [
    "//! The evdev key codes by name, lowercase and without the `KEY_` prefix,",
    "//! sorted for a binary search.",
    "//!",
    "//! Origin: the `KEY_*` defines of `linux/input-event-codes.h` (Linux uapi",
    f"//! header, linux-libc-dev {LIBC_DEV}), `KEY_RESERVED`, `KEY_MIN_INTERESTING`,",
    "//! `KEY_MAX` and `KEY_CNT` left out, aliases resolved to their value.",
    "//! Licence of the header: GPL-2.0-only WITH Linux-syscall-note; the note",
    "//! puts user programs that use the kernel interface, such as these code",
    "//! numbers, outside the GPL. Generated by `tools/keycodes/generate.py`;",
    "//! never edit by hand.",
    "",
    "/// `(name, code)` pairs, sorted by name.",
    "pub(super) const KEYCODES: &[(&str, u16)] = &[",
]
lines += [f'    ("{name}", {code}),' for name, code in rows]
lines.append("];")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(rows)} key codes -> {OUT}")
