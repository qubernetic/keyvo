#!/usr/bin/env python3
"""Generate crates/keyvo-core/assets/lucide/*.svg and
crates/keyvo-core/src/render/icon/lucide.rs from the pinned lucide release.

Usage, from the repository root:

    python3 tools/lucide/generate.py [lucide-icons-<VERSION>.zip]

Without an argument the script downloads the release asset. Either way it
checks the archive's sha256 before it writes anything. The asset carries
every icon as `icons/<name>.svg` next to its metadata `icons/<name>.json`,
whose `aliases` are the deprecated names the renderer still resolves.

To bump lucide, move VERSION and SHA256 together, run the script, then
`just fmt lint test`.
"""

import hashlib
import io
import json
import sys
import urllib.request
import zipfile
from pathlib import Path

VERSION = "1.61.0"
SHA256 = "d4cfe5949e0cf202ec558c3fe2cc6c8373371c1cb8643fac2f7c68ce4153ff4b"
ASSET = f"lucide-icons-{VERSION}.zip"
URL = f"https://github.com/lucide-icons/lucide/releases/download/{VERSION}/{ASSET}"

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "crates/keyvo-core/assets/lucide"
OUT = ROOT / "crates/keyvo-core/src/render/icon/lucide.rs"
SVG_HEADER = (
    f"<!-- lucide {VERSION}, https://github.com/lucide-icons/lucide, "
    "ISC licence (LICENSE in this directory) -->\n"
)


def archive() -> bytes:
    if len(sys.argv) > 1:
        data = Path(sys.argv[1]).read_bytes()
    else:
        with urllib.request.urlopen(URL) as response:
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{ASSET}: sha256 {digest}, expected {SHA256}; nothing written")
    return data


def read_icons(data: bytes) -> tuple[dict[str, bytes], dict[str, str]]:
    icons, aliases = {}, {}
    with zipfile.ZipFile(io.BytesIO(data)) as zip_file:
        for entry in zip_file.namelist():
            if entry.startswith("icons/") and entry.endswith(".svg"):
                icons[entry[len("icons/") : -len(".svg")]] = zip_file.read(entry)
        for name in icons:
            meta = json.loads(zip_file.read(f"icons/{name}.json"))
            for alias in meta.get("aliases", []):
                alias = alias["name"] if isinstance(alias, dict) else alias
                if alias in icons or alias in aliases:
                    sys.exit(f"alias `{alias}` of `{name}` is taken; nothing written")
                aliases[alias] = name
    return icons, aliases


def rust(icons: dict[str, bytes], aliases: dict[str, str]) -> str:
    lines = [
        f"//! The lucide icons keyvo bundles: every icon of lucide {VERSION}",
        "//! (<https://github.com/lucide-icons/lucide>, ISC licence, text in",
        "//! `assets/lucide/LICENSE`) and the deprecated names of its metadata.",
        f"//! Origin: the release asset `{ASSET}`. Generated by",
        "//! `tools/lucide/generate.py`; never edit by hand.",
        "",
        "/// `(name, svg)` pairs, sorted by name.",
        "#[rustfmt::skip]",
        "pub(super) const LUCIDE: &[(&str, &str)] = &[",
    ]
    lines += [
        f'    ("{name}", include_str!("../../../assets/lucide/{name}.svg")),'
        for name in sorted(icons)
    ]
    lines += [
        "];",
        "",
        "/// `(deprecated name, icon)` pairs, sorted by the deprecated name.",
        "#[rustfmt::skip]",
        "pub(super) const LUCIDE_ALIASES: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{alias}", "{aliases[alias]}"),' for alias in sorted(aliases)]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> None:
    icons, aliases = read_icons(archive())
    for stale in ASSETS.glob("*.svg"):
        if stale.stem not in icons:
            stale.unlink()
    for name, svg in icons.items():
        (ASSETS / f"{name}.svg").write_bytes(SVG_HEADER.encode() + svg)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(rust(icons, aliases), encoding="utf-8")
    print(f"{len(icons)} icons, {len(aliases)} aliases -> {ASSETS}, {OUT}")


main()
